import type { SizeSpec } from './types';

export interface PackImageEntry {
  name: string;
  role: string;
  size: SizeSpec;
}

export interface PackPlan {
  images: PackImageEntry[];
  manifestName: string;
  readmeName: string;
}

/** Conventional favicon sizes always included in the pack when available. */
const FAVICON_PNG_SIZES = [16, 32];
const APPLE_TOUCH_SIZE = 180;
const ANDROID_SIZES = [192, 256];

function has(sizes: SizeSpec[], w: number, h: number): boolean {
  return sizes.some((s) => s.w === w && s.h === h);
}

/**
 * Compute the conventional pack layout. Each selected size contributes a
 * `name-<W>x<H>.png`, plus conventional favicon/apple-touch/android-chrome
 * assets rendered at their standard sizes (clamped to the 16–256 range).
 */
export function planPack(base: string, sizes: SizeSpec[]): PackPlan {
  const images: PackImageEntry[] = [];

  // Per-size PNGs for every selected size.
  for (const s of sizes) {
    images.push({ name: `${base}-${s.w}x${s.h}.png`, role: 'size', size: s });
  }

  // Conventional favicon PNGs (only if not already covered by a selected size).
  for (const n of FAVICON_PNG_SIZES) {
    if (!has(sizes, n, n)) {
      images.push({ name: `favicon-${n}x${n}.png`, role: 'favicon', size: { w: n, h: n } });
    }
  }

  // Apple touch icon (180). Clamp to 256 max.
  const apple = Math.min(APPLE_TOUCH_SIZE, 256);
  if (!has(sizes, apple, apple)) {
    images.push({ name: 'apple-touch-icon.png', role: 'apple-touch', size: { w: apple, h: apple } });
  }

  // Android chrome icons.
  for (const n of ANDROID_SIZES) {
    const clamped = Math.min(n, 256);
    if (!has(sizes, clamped, clamped)) {
      images.push({ name: `android-chrome-${clamped}x${clamped}.png`, role: 'android', size: { w: clamped, h: clamped } });
    }
  }

  return { images, manifestName: 'site.webmanifest', readmeName: 'README.txt' };
}

export interface ManifestIcon {
  src: string;
  sizes: string;
  type: string;
  purpose?: string;
}

/** Build the site.webmanifest object referencing the generated PNG assets. */
export function buildManifest(plan: PackPlan, base: string): Record<string, unknown> {
  const icons: ManifestIcon[] = [];
  for (const img of plan.images) {
    if (img.role === 'size' || img.role === 'favicon' || img.role === 'android') {
      icons.push({ src: img.name, sizes: `${img.size.w}x${img.size.h}`, type: 'image/png' });
    }
  }
  // Mark the 192/256 android icons as maskable-capable purpose where present.
  for (const icon of icons) {
    if (/android-chrome/.test(icon.src)) icon.purpose = 'any maskable';
  }
  return {
    name: base,
    short_name: base,
    icons,
    theme_color: '#7c3aed',
    background_color: '#ffffff',
    display: 'standalone',
    start_url: '/',
  };
}

export function buildReadme(base: string, plan: PackPlan): string {
  const lines: string[] = [];
  lines.push(`# ${base} — icon pack`);
  lines.push('');
  lines.push('Generated by IconKiln. All processing happened locally in your browser; nothing was uploaded.');
  lines.push('');
  lines.push('## Files');
  for (const img of plan.images) {
    lines.push(`- ${img.name} (${img.size.w}x${img.size.h})`);
  }
  lines.push(`- ${plan.manifestName} (web app manifest)`);
  lines.push(`- ${plan.readmeName} (this file)`);
  lines.push('');
  lines.push('## Usage');
  lines.push('- Drop favicon.ico at your site root for legacy/rel=icon support.');
  lines.push('- Link the PNG icons and apple-touch-icon in your HTML <head>.');
  lines.push(`- Reference ${plan.manifestName} via <link rel="manifest" href="/site.webmanifest">.`);
  lines.push('');
  lines.push('Part of the AaronWiseAI open-source tool collection — https://aaronwiseai.com/');
  lines.push('');
  return lines.join('\n');
}