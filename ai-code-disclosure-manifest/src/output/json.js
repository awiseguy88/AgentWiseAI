/**
 * JSON Output Generator
 * Produces machine-readable disclosure manifest
 * Zero dependencies — Node.js stdlib only
 */

/**
 * Generate JSON manifest from scan results
 * @param {Object} results - Output from scanRepository
 * @returns {string} JSON string
 */
function generateJSON(results) {
  const output = {
    manifestVersion: '1.0',
    generatedAt: results.scanInfo.scannedAt,
    repository: results.scanInfo.repository,
    scanOptions: results.scanInfo.options,
    scanInfo: {
      commitsScanned: results.scanInfo.commitCount,
      filesScanned: results.scanInfo.fileCount,
      commitsWithFindings: results.summary.commitsWithFindings,
      filesWithFindings: results.summary.filesWithFindings,
      options: results.scanInfo.options,
    },
    summary: results.summary,
    findings: {
      commits: results.commits.map(c => ({
        hash: c.commitHash,
        date: c.commitDate,
        author: c.author,
        findings: c.findings.map(f => ({
          type: f.type,
          confidence: f.confidence,
          signal: f.signal,
          location: f.location,
          tool: f.tool || null,
        })),
      })),
      files: results.files.map(f => ({
        file: f.file,
        findings: f.findings.map(fi => ({
          type: fi.type,
          confidence: fi.confidence,
          signal: fi.signal,
          location: fi.location,
          tool: fi.tool || null,
        })),
      })),
    },
    templates: generateTemplates(results.summary),
  };

  return JSON.stringify(output, null, 2);
}

/**
 * Generate notice templates based on scan summary
 * @param {Object} summary
 * @returns {Object} Template strings
 */
function generateTemplates(summary) {
  const hasAIFindings = summary.totalFindings > 0;
  const highConfidence = summary.byConfidence.high || 0;
  const mediumConfidence = summary.byConfidence.medium || 0;
  const tools = Object.keys(summary.byTool || {}).join(', ') || 'unknown AI tools';

  const lowConfidence = summary.byConfidence.low || 0;
  return {
    disclosure: generateDisclosureNotice(hasAIFindings, highConfidence, mediumConfidence, tools, lowConfidence),
    attribution: generateAttributionNotice(hasAIFindings, tools),
    cc0: generateCC0Notice(hasAIFindings),
    oss: generateOSSNotice(hasAIFindings),
  };
}

/**
 * Disclosure notice - for README or CONTRIBUTING
 */
function generateDisclosureNotice(hasFindings, high, medium, tools, low = 0) {
  const lines = [
    '# AI Code Disclosure',
    '',
    'This repository contains code that was assisted by AI tools.',
  ];

  if (hasFindings) {
    const total = (high || 0) + (medium || 0) + (low || 0);
    lines.push(
      '',
      `## Scan Results (as of ${new Date().toISOString().split('T')[0]})`,
      '',
      `- **Total AI signals detected:** ${total}`,
      `- **High confidence:** ${high || 0}`,
      `- **Medium confidence:** ${medium || 0}`,
      `- **Tools identified:** ${tools}`,
      '',
      'These signals were detected through commit history analysis and source code scanning for common AI-assist markers (co-author trailers, generated headers, prompt comments, tool signatures).',
      '',
      '> **Note:** This disclosure is generated automatically and may not capture all AI assistance. Absence of signals does not guarantee no AI tools were used.'
    );
  } else {
    lines.push(
      '',
      'No AI-assist markers were detected in the current scan.',
      '> **Note:** This scan only detects explicit markers. AI assistance without explicit markers may not be captured.'
    );
  }

  lines.push(
    '',
    '---',
    '',
    'Generated by [AI Code Disclosure Manifest](https://github.com/awiseguy88/AgentWiseAI/tree/main/ai-code-disclosure-manifest) — an offline-first tool for AI code provenance.',
    'Part of the AaronWiseAI tool collection — https://aaronwiseai.com/'
  );

  return lines.join('\n');
}

/**
 * Attribution notice - for LICENSE or NOTICE file
 */
function generateAttributionNotice(hasFindings, tools) {
  const lines = [
    '# Attribution Notice',
    '',
    'Portions of this codebase were developed with the assistance of AI tools.',
  ];

  if (hasFindings) {
    lines.push(
      '',
      `## AI Tools Used`,
      '',
      tools.split(', ').map(t => `- ${t.trim()}`).join('\n'),
      '',
      '## Human Authorship',
      '',
      'Human authors retain copyright and responsibility for all code in this repository, including AI-assisted portions. AI tools were used as assistants under human direction and review.',
      '',
      '## Verification',
      '',
      'AI-assisted code has been reviewed, tested, and validated by human maintainers before inclusion.'
    );
  } else {
    lines.push(
      '',
      'No specific AI tools were identified in the automated scan. This notice is included as a general disclosure.',
      '',
      'Human authors retain full copyright and responsibility for all code in this repository.'
    );
  }

  lines.push(
    '',
    '---',
    '',
    'Generated by AI Code Disclosure Manifest — Part of the AaronWiseAI tool collection — https://aaronwiseai.com/'
  );

  return lines.join('\n');
}

