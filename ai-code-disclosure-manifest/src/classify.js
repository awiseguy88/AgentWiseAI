/**
 * AI Marker Classification Engine
 * Detects and scores AI-assist signals in commit messages and source files
 * Zero dependencies — Node.js stdlib only
 */

const { truncate } = require('./utils');

// Known AI agent/bot email patterns (GitHub noreply domains with bot-like names)
const BOT_EMAIL_PATTERNS = [
  /^[^@]+@users\.noreply\.github\.com$/i,
  /^[^@]+@github\.com$/i, // generic, but we check name too
];

// Known AI tool names for signature matching
const AI_TOOL_NAMES = [
  'github copilot', 'copilot',
  'cursor', 'cursor ai',
  'claude', 'claude code', 'claude.ai', 'anthropic',
  'deepseek', 'deepseek coder', 'deepseek-chat',
  'chatgpt', 'chat gpt', 'openai', 'gpt-4', 'gpt-3.5',
  'tabnine', 'codeium', 'codewhisperer', 'amazon q',
  'replit', 'replit ai', 'ghostwriter',
  'sourcegraph cody', 'cody',
  'continue', 'continue.dev',
  'aider', 'aider.chat',
  'windsurf', 'codeium windsurf',
  'vscode', 'visual studio code', // generic but often with AI extensions
  'zed', 'zed editor',
  'neovim', 'vim', // with AI plugins
];

// Commit trailer patterns that strongly indicate AI generation
const HIGH_CONFIDENCE_TRAILERS = [
  /^generated-by:/i,
  /^ai-generated:/i,
  /^agent:/i,
  /^created-by:/i,
  /^tool:/i,
];

// Commit message patterns
const COMMIT_PATTERNS = {
  high: [
    /generated by\s+/i,
    /created with\s+/i,
    /ai[- ]?assisted/i,
    /co[- ]?authored by\s+(?:github )?copilot/i,
    /written by\s+(?:github )?copilot/i,
  ],
  medium: [
    /ai[- ]?generated/i,
    /machine[- ]?generated/i,
    /auto[- ]?generated/i,
    /prompt:/i,
    /copilot/i,
    /claude/i,
    /deepseek/i,
    /cursor/i,
    /tabnine/i,
    /codeium/i,
    /codewhisperer/i,
  ],
  low: [
    /\bai\b/i,
    /\bgpt\b/i,
    /\bllm\b/i,
    /assistant/i,
    /automated/i,
  ],
};

// Source file header patterns (first ~30 lines)
const HEADER_PATTERNS = {
  high: [
    /^\s*\/\/\s*generated by\s+/i,
    /^\s*\/\/\s*created (?:with|by)\s+/i,
    /^\s*\/\*\s*generated by\s+/i,
    /^\s*\/\*\s*ai[- ]?generated\s*\*\//i,
    /^\s*#\s*generated by\s+/i,
    /^\s*#\s*ai[- ]?generated/i,
    /^\s*---\s*generated by\s+/i,
    /^\s*\/\/\s*@generated/i,
  ],
  medium: [
    /^\s*\/\/\s*ai:/i,
    /^\s*\/\/\s*copilot:/i,
    /^\s*\/\/\s*claude:/i,
    /^\s*\/\/\s*prompt:/i,
    /^\s*\/\*\s*prompt:/i,
    /^\s*#\s*prompt:/i,
    /^\s*\/\/\s*todo\(ai\):/i,
    /^\s*\/\/\s*fixme\(ai\):/i,
  ],
  low: [
    /^\s*\/\/\s*auto[- ]?generated/i,
    /^\s*\/\/\s*machine[- ]?generated/i,
    /^\s*#\s*auto[- ]?generated/i,
  ],
};

// Inline comment patterns (anywhere in file)
const INLINE_PATTERNS = {
  medium: [
    /\/\/\s*ai:/gi,
    /\/\/\s*copilot:/gi,
    /\/\/\s*claude:/gi,
    /\/\/\s*prompt:/gi,
    /\/\/\s*deepseek:/gi,
    /\/\/\s*cursor:/gi,
    /\/\/\s*todo\(ai\)/gi,
    /\/\/\s*fixme\(ai\)/gi,
    /#\s*ai:/gi,
    /#\s*copilot:/gi,
    /#\s*prompt:/gi,
    /<!--\s*ai:/gi,
    /<!--\s*prompt:/gi,
  ],
  low: [
    /\/\/\s*ai\s+/gi,
    /\/\/\s*generated\s+/gi,
    /#\s*ai\s+/gi,
    /#\s*generated\s+/gi,
  ],
};

/**
 * Check if an email looks like a known bot/AI agent
 * @param {string} email
 * @param {string} name
 * @returns {boolean}
 */
function isBotEmail(email, name = '') {
  if (!email) return false;
  const lowerEmail = email.toLowerCase();
  const lowerName = name.toLowerCase();

  // Known bot email domains
  if (lowerEmail.endsWith('@users.noreply.github.com')) {
    // Check for bot-like names
    const botNames = ['bot', 'copilot', 'claude', 'deepseek', 'cursor', 'tabnine', 'codeium', 'cody', 'aider', 'windsurf', 'github-actions', 'github-action', 'dependabot', 'renovate', 'codecov', 'codacy'];
    return botNames.some(bn => lowerName.includes(bn) || lowerEmail.includes(bn));
  }
  return false;
}

/**
 * Check if a string contains known AI tool name
 * @param {string} str
 * @returns {string|null} Matched tool name or null
 */
function findAIToolName(str) {
  const lower = str.toLowerCase();
  for (const tool of AI_TOOL_NAMES) {
    if (lower.includes(tool)) return tool;
  }
  return null;
}

/**
 * Classify a commit for AI markers
 * @param {Object} commit - Commit object from utils.getCommitDetails
 * @returns {Object} Classification result
 */
function classifyCommit(commit) {
  const findings = [];
  const message = (commit.rawMessage || '').toLowerCase();
  const subject = (commit.subject || '').toLowerCase();
  const body = (commit.body || '').toLowerCase();

  // Check trailers (high confidence)
  const trailerMatches = [];
  const fullMessage = commit.rawMessage || '';
  const trailerLines = fullMessage.split('\n').filter(l => l.includes(':'));
  for (const line of trailerLines) {
    const trimmed = line.trim();
    for (const pattern of HIGH_CONFIDENCE_TRAILERS) {
      if (pattern.test(trimmed)) {
        trailerMatches.push({ pattern: pattern.source, text: trimmed });
        findings.push({
          type: 'trailer',
          confidence: 'high',
          signal: trimmed,
          location: 'commit trailer',
        });
      }
    }
    // Check for Co-Authored-By with bot email
    if (/^co-authored-by:/i.test(trimmed)) {
      const match = trimmed.match(/^co-authored-by:\s*(.+?)\s*<(.+?)>$/i);
      if (match) {
        const [, name, email] = match;
        if (isBotEmail(email, name)) {
          findings.push({
            type: 'co-author',
            confidence: 'high',
            signal: `Co-Authored-By: ${name} <${email}>`,
            location: 'commit trailer',
            tool: findAIToolName(name) || findAIToolName(email),
          });
        }
      }
    }
  }

  // Check commit message patterns
  const checkPatterns = (text, location) => {
    for (const [confidence, patterns] of Object.entries(COMMIT_PATTERNS)) {
      for (const pattern of patterns) {
        if (pattern.test(text)) {
          const tool = findAIToolName(text);
          findings.push({
            type: 'commit-message',
            confidence,
            signal: truncate(text.match(pattern)?.[0] || text.slice(0, 80)),
            location,
            tool,
          });
        }
      }
    }
  };

  checkPatterns(subject, 'commit subject');
  if (body) checkPatterns(body, 'commit body');

  // Deduplicate similar findings
  const unique = [];
  const seen = new Set();
  for (const f of findings) {
    const key = `${f.type}:${f.confidence}:${f.signal.slice(0, 50)}`;
    if (!seen.has(key)) {
      seen.add(key);
      unique.push(f);
    }
  }

  return {
    commitHash: commit.hash,
    commitDate: commit.date,
    author: commit.author,
    subject: commit.subject,
    findings: unique,
    highestConfidence: unique.length ? unique.reduce((a, b) => 
      confidenceRank(b.confidence) > confidenceRank(a.confidence) ? b : a
    ).confidence : 'none',
  };
}

/**
 * Classify a source file for AI markers
 * @param {string} filePath - Absolute path to file
 * @param {string} content - File content
 * @param {string} repoRoot - Repository root for relative path
 * @returns {Object} Classification result
 */
function classifyFile(filePath, content, repoRoot) {
  const findings = [];
  const relPath = repoRoot ? require('path').relative(repoRoot, filePath) : filePath;
  const lines = content.split('\n');
  const headerLines = lines.slice(0, 50).join('\n'); // First 50 lines for headers

  // Check header patterns
  for (const [confidence, patterns] of Object.entries(HEADER_PATTERNS)) {
    for (const pattern of patterns) {
      const match = headerLines.match(pattern);
      if (match) {
        const tool = findAIToolName(match[0]);
        findings.push({
          type: 'file-header',
          confidence,
          signal: truncate(match[0]),
          location: `file header (${relPath})`,
          tool,
          file: relPath,
        });
      }
    }
  }

  // Check inline patterns (whole file)
  for (const [confidence, patterns] of Object.entries(INLINE_PATTERNS)) {
    for (const pattern of patterns) {
      let match;
      while ((match = pattern.exec(content)) !== null) {
        const tool = findAIToolName(match[0]);
        // Find line number
        const beforeMatch = content.slice(0, match.index);
        const lineNum = beforeMatch.split('\n').length;
        findings.push({
          type: 'inline-comment',
          confidence,
          signal: truncate(match[0]),
          location: `${relPath}:${lineNum}`,
          tool,
          file: relPath,
        });
        // Avoid infinite loop on zero-width matches
        if (match[0].length === 0) break;
      }
    }
  }

  // Deduplicate
  const unique = [];
  const seen = new Set();
  for (const f of findings) {
    const key = `${f.type}:${f.confidence}:${f.location}:${f.signal.slice(0, 40)}`;
    if (!seen.has(key)) {
      seen.add(key);
      unique.push(f);
    }
  }

  return {
    file: relPath,
    findings: unique,
    highestConfidence: unique.length ? unique.reduce((a, b) => 
      confidenceRank(b.confidence) > confidenceRank(a.confidence) ? b : a
    ).confidence : 'none',
  };
}

/**
 * Rank confidence for comparison
 * @param {string} confidence
 * @returns {number}
 */
function confidenceRank(confidence) {
  const ranks = { high: 3, medium: 2, low: 1, none: 0 };
  return ranks[confidence] || 0;
}

/**
 * Filter findings by minimum confidence
 * @param {Object[]} findings
 * @param {string} minConfidence - 'high', 'medium', 'low', or 'all'
 * @returns {Object[]}
 */
function filterByConfidence(findings, minConfidence = 'all') {
  if (minConfidence === 'all') return findings;
  const minRank = confidenceRank(minConfidence);
  return findings.filter(f => confidenceRank(f.confidence) >= minRank);
}

/**
 * Summarize findings across commits and files
 * @param {Object[]} commitResults
 * @param {Object[]} fileResults
 * @returns {Object} Summary counts
 */
function summarize(commitResults, fileResults) {
  const allFindings = [
    ...commitResults.flatMap(c => c.findings.map(f => ({ ...f, source: 'commit', commitHash: c.commitHash }))),
    ...fileResults.flatMap(f => f.findings.map(fi => ({ ...fi, source: 'file', file: f.file }))),
  ];

  const byConfidence = { high: 0, medium: 0, low: 0 };
  const byType = {};
  const byTool = {};

  for (const f of allFindings) {
    byConfidence[f.confidence] = (byConfidence[f.confidence] || 0) + 1;
    byType[f.type] = (byType[f.type] || 0) + 1;
    if (f.tool) byTool[f.tool] = (byTool[f.tool] || 0) + 1;
  }

  return {
    totalFindings: allFindings.length,
    byConfidence,
    byType,
    byTool,
    commitsScanned: commitResults.length,
    filesScanned: fileResults.length,
    commitsWithFindings: commitResults.filter(c => c.findings.length).length,
    filesWithFindings: fileResults.filter(f => f.findings.length).length,
  };
}

